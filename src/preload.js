const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ws', {
  barHeight: (px) => ipcRenderer.send('bar-height', px),
  listWindows: () => ipcRenderer.invoke('list-windows'),
  overlay: (name) => ipcRenderer.send('overlay', name),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  setSetting: (key, value) => ipcRenderer.send('set-setting', key, value),
  add: (hwnd) => ipcRenderer.send('add', hwnd),
  activate: (hwnd) => ipcRenderer.send('activate', hwnd),
  detach: (hwnd) => ipcRenderer.send('detach', hwnd),
  detachTab: (hwnd) => ipcRenderer.send('detach-tab', hwnd),
  detachDrop: (hwnd) => ipcRenderer.send('detach-drop', hwnd),
  reorder: (hwnd, to) => ipcRenderer.send('reorder', hwnd, to),
  tabMenu: (hwnd) => ipcRenderer.send('tab-menu', hwnd),
  splitRatio: (hwnd, axis, ratio, done) => ipcRenderer.send('split-ratio', hwnd, axis, ratio, done),
  onBars: (cb) => ipcRenderer.on('bars', (_e, layout) => cb(layout)),
  restore: () => ipcRenderer.invoke('restore'),
  onTabs: (cb) => ipcRenderer.on('tabs', (_e, state) => cb(state)),
  onWorkspaces: (cb) => ipcRenderer.on('workspaces', (_e, list) => cb(list)),
  createWorkspace: (name, items) => ipcRenderer.invoke('workspace-create', name, items),
  updateWorkspace: (id, patch) => ipcRenderer.send('workspace-update', id, patch),
  deleteWorkspace: (id) => ipcRenderer.send('workspace-delete', id),
  launchWorkspace: (id) => ipcRenderer.invoke('workspace-launch', id),
  pickPrograms: () => ipcRenderer.invoke('pick-programs'),
  onDropHint: (cb) => ipcRenderer.on('drop-hint', (_e, zone) => cb(zone)),
  onCloseOverlay: (cb) => ipcRenderer.on('close-overlay', () => cb()),
  updateState: () => ipcRenderer.invoke('update-state'),
  checkUpdate: () => ipcRenderer.send('update-check'),
  installUpdate: () => ipcRenderer.send('update-install'),
  onUpdate: (cb) => ipcRenderer.on('update', (_e, state) => cb(state)),
});
